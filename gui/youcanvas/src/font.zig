    var cy = y;
    for (text) |ch| {
        if (ch == '\n') {
            cx = start_x;
            cy += 16;
            continue;
        }
        draw_glyph_large(canvas, cx, cy, glyph_bits_large(ch), color);
        cx += 9;
    }
}

fn draw_glyph_large(canvas: Canvas, x: i32, y: i32, bits: [16]u8, color: u32) void {
    for (bits, 0..) |row_bits, row| {
        if (row_bits == 0) continue;
        var col: u3 = 0;
        while (col < 8) : (col += 1) {
            if (((row_bits >> (7 - col)) & 1) != 0) {
                const px = x + @as(i32, col);
                const py = y + @as(i32, @intCast(row));
                if (px >= 0 and py >= 0 and px < @as(i32, @intCast(canvas.width)) and py < @as(i32, @intCast(canvas.height))) {
                    canvas.ptr[@as(usize, @intCast(py)) * @as(usize, canvas.width) + @as(usize, @intCast(px))] = color;
                }
            }
        }
    }
}

