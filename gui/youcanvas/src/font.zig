pub fn text_width(text: []const u8) u32 {
    var max: u32 = 0;
    var line: u32 = 0;
    for (text) |ch| {
        if (ch == '\n') {
            max = @max(max, line);
            line = 0;
        } else {
            line += 6;
        }
    }
    return @max(max, line);
}

pub fn draw_text(canvas: Canvas, x: i32, y: i32, text: []const u8, color: u32) void {
    const start_x = x;
    var cx = x;
    var cy = y;
    for (text) |ch| {
        if (ch == '\n') {
            cx = start_x;
            cy += 8;
            continue;
        }
        draw_glyph(canvas, cx, cy, glyph_bits(ch), color);
        cx += 6;
    }
}

fn draw_glyph(canvas: Canvas, x: i32, y: i32, bits: [7]u8, color: u32) void {
    for (bits, 0..) |row_bits, row| {
        var col: u3 = 0;
        while (col < 5) : (col += 1) {
            if (((row_bits >> (4 - col)) & 1) != 0) {
                const px = x + @as(i32, col);
                const py = y + @as(i32, @intCast(row));
                if (px >= 0 and py >= 0 and px < @as(i32, @intCast(canvas.width)) and py < @as(i32, @intCast(canvas.height))) {
                    canvas.ptr[@as(usize, @intCast(py)) * @as(usize, canvas.width) + @as(usize, @intCast(px))] = color;
                }
            }
        }
    }
}

